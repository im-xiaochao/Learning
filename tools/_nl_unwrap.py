# -*- coding: utf-8 -*-
"""去掉题库文本里的 **PDF 排版换行**，只保留真正的段落分隔。

## 为什么需要

`explanation` / `answerPoints` 来自《答案解析》PDF 的**文本层**，文本层把每一行排版
都保留了。这些换行在 TS 里是 `\\n` 转义 → 小程序渲染成真换行 → 用户在**词中间**看到
断行（`大洋` | `洲`、`1` | `亿人`、`第` | `二`）。

## 判据

文本层里段落分隔**没有单独标记**（91k 字符里只有 1 个空行），所以「真段落」和「排版
换行」在纯文本里是同一种东西。但中文 PDF **两端对齐**：

    **满行 ⟺ 段落未完**；段落末行必然短。

所以「这个换行是不是真段落分隔」= 「**前一行是否明显短于满行宽度**」。

实测断行点前一行的视觉宽度（ASCII 算 0.5 宽）：

    肖八：满行 36~44（峰值 39~40），短行 ≤35
    肖四：满行 36~46（峰值 41~42），短行 ≤35

两套一致，取 **36** 作阈值。

再叠加一个条件「前一行以句末标点结尾」，用来排除**短行但不是段落末行**的情况——
典型是公式被 OCR 丢掉、只剩一个字独占一行：

    即
    则可变资本（v）为20万元。其预付
    资本为100万元，则不变资本（c）为80万元。

`即` 是短行，但它不是段落末行（公式是图片，文本层只剩一个字），靠「以句末标点结尾」
这条把它排除，避免在 `其预付` | `资本` 这种词中间留一个换行。

## 误判是良性的

两个方向的误判都不产生「词中间断行」——那才是用户一眼看得出的问题：
  · 多留一个换行 → 多一个分段（轻微）
  · 少留一个换行 → 两个段落合并（轻微）

## ⚠️ 这是**单向**操作，不是幂等的

合并之后，原始的行宽信息就没了——合并出来的段落在「前行满行」判据下**必然**
被判成排版换行。所以对同一份文本连跑两次，第二次会把真段落也吃掉：

    第 1 次：973 个换行 → 61 个（61 个真段落）
    第 2 次： 61 个换行 →  0 个（段落结构被抹平）

`unwrap()` 因此带了 `looks_unwrapped()` 短路保护（判据见该函数），调用方
（`_x4_unwrap.py`）另有文件级前置检查。
"""
import re

# 满行阈值：视觉宽度 ≥ 它就认为「段落未完」
FULL_W = 36.0
# 排版行的宽度上限（实测《答案解析》文本层最长 45）。合并后的段落会远超它——
# 肖四合并后最长 461。60 落在两者之间。
LAYOUT_MAX_W = 60.0
# 真段落末行几乎必然以句末标点结尾（排除公式残留、图表注等短行）
PARA_END = ("。", "！", "？", "；", "”", "》", "…")

# `材料 1` / `材料 2` 是**故意**的换行（材料分栏标题），必须保留
KEEP_LINE = re.compile(r"^材料\s*\d\s*$")


def vwidth(s: str) -> float:
    """视觉宽度：汉字/全角标点算 1，ASCII 算 0.5。"""
    return sum(0.5 if ord(c) < 128 else 1.0 for c in s)


def looks_unwrapped(t: str) -> bool:
    """这段文本是否**已经**去过排版换行。

    ⚠️ 不能用「存在超宽行」判——**原始**文本里也有少数超宽行（OCR 把相邻两行并进
    一个框；肖四原始 1122 行里有 23 行 >60，占 2%）。必须用**比例**：处理前只有 2%
    的行超宽，处理后是 91%，所以取「**过半**」作分界。
    """
    ls = [l for l in t.split("\n") if l]
    if not ls:
        return False
    return sum(1 for l in ls if vwidth(l) > LAYOUT_MAX_W) * 2 > len(ls)


def unwrap(t: str) -> str:
    """把排版换行拼掉，只留真段落分隔。

    ⚠️ **单向操作**：对已处理过的文本再调一次会把真段落也吃掉，所以这里用
    `looks_unwrapped` 短路。对**原始**文本单次调用是正确的。
    """
    if not t or "\n" not in t:
        return t
    if looks_unwrapped(t):
        return t          # 已经 unwrap 过，原样返回（幂等保护）
    lines = t.split("\n")
    out = [lines[0]]
    for i in range(1, len(lines)):
        cur = lines[i]
        # `材料 N` 标题自己独占一行，保留它**前面**的换行
        if KEEP_LINE.match(cur.strip()):
            out.append(cur)
            continue
        prev = lines[i - 1]
        # ⚠️ `材料 N` 与正文之间**也**要保留。上面那条 `KEEP_LINE.match(cur)` 只挡住
        # 了「`材料 N` 前面的换行」，轮到下一行（正文）时 `prev` 是 `材料 N`，宽度 4 < 36
        # 又不以句末标点结尾 → 会被判成排版换行合并掉，标题就粘进正文了：
        #     `材料 1` + `习近平…` → `材料 1习近平…`   （分栏标题失效）
        # 所以这里补「`材料 N` 后面」的换行。
        if KEEP_LINE.match(prev.strip()):
            out.append(cur)
            continue
        # 必须用**原始**前一行判宽度，不能用 `out[-1]`——它已经合并了若干行，
        # 宽度必然超过阈值，后面所有换行都会被误判成排版换行（踩过）。
        if vwidth(prev) < FULL_W and prev.rstrip().endswith(PARA_END):
            out.append(cur)        # 真段落分隔
        else:
            out[-1] += cur         # 排版换行 → 直接拼接（中文不需要空格）
    return "\n".join(out)
