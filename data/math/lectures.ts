export interface MathLecture {
  title: string
  tag: string
  explanation: string
  keyPoints: string[]
  formula?: string
  example?: string
  trap?: string
  visual: MathVisualKind
  steps: string[]
  /** 通用兜底讲义：没有专属讲解时才会为 true，页面据此判断知识关系图是否值得展示。 */
  generic?: boolean
  /** 内容出处（讲次对应），有出处时页面会在标签区展示。 */
  source?: string
}

type LectureBody = Omit<MathLecture, 'title'>

function body(
  tag: string,
  explanation: string,
  keyPoints: string[],
  visual: MathVisualKind,
  steps: string[],
  formula?: string,
  example?: string,
  trap?: string,
  source?: string,
): LectureBody {
  return {
    tag,
    explanation,
    keyPoints,
    visual,
    steps,
    ...(formula ? { formula } : {}),
    ...(example ? { example } : {}),
    ...(trap ? { trap } : {}),
    ...(source ? { source } : {}),
  }
}

function cleanTopic(topic: string): string {
  return topic
    .replace(/\u0060/g, '')
    .replace(/^第[一二三四五六七八九十0-9]+章\s*/, '')
    .replace(/^\d+(?:\.\d+)+\s*/, '')
    .replace(/^\d+[.、]\s*/, '')
    .replace(/[。；;]+$/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

